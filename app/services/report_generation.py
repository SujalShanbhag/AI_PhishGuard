class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas that writes dynamic 'Page X of Y' footers
    and running forensic headers across multi-page documents.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica-Bold", 7.5)
        self.setFillColor(colors.HexColor("#475569"))

        # Running Top Header
        self.drawString(40, 755, "AI PHISHGUARD — DIGITAL EVIDENCE & FORENSIC INVESTIGATION REPORT")
        self.setFont("Helvetica", 7)
        self.drawRightString(572, 755, "EVIDENTIARY AUDIT RECORD // CONFIDENTIAL")
        self.setStrokeColor(colors.HexColor("#94a3b8"))
        self.setLineWidth(0.5)
        self.line(40, 747, 572, 747)

        # Running Bottom Footer
        self.line(40, 42, 572, 42)
        self.setFont("Helvetica", 7)
        self.drawString(40, 30, "AI PHISHGUARD FORENSICS LAB // ISO/IEC 27037:2012 & NIST SP 800-86 COMPLIANT")
        self.drawRightString(572, 30, f"Page {self._pageNumber} of {page_count}")
        self.restoreState()


